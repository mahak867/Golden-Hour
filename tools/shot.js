const { chromium } = require('playwright');
const path = require('path');
const OUT = process.argv[2] || path.resolve(__dirname, '../screenshots');
const SCALE = Number(process.argv[3] || 2);
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: SCALE });
  p.on('pageerror', e => console.log('PAGEERROR', e.message));
  p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
  await p.goto('file://' + path.resolve(__dirname, '../index.html') + '?autoplay=1&speed=0.12');
  await p.waitForFunction(() => document.title === 'DONE', null, { timeout: 120000 });
  await p.evaluate(() => { hideCard(); document.getElementById('cursor').classList.remove('on'); });
  await p.waitForTimeout(700);
  const snap = async (view, file, prep) => { await p.evaluate(v => show(v), view); if (prep) await p.evaluate(prep); await p.waitForTimeout(1100); await p.screenshot({ path: path.join(OUT, file) }); };
  await snap('console', 'bank-console.png', () => { selAcct = 'XXXX4471'; renderConsole(); });
  await snap('impact', 'impact.png');
  await snap('rules', 'rules.png');
  await snap('victim', 'victim-flow.png', () => openTab('routes'));
  await p.locator('.device').screenshot({ path: path.join(OUT, 'telegram-chat.png') });
  await p.evaluate(() => openTab('evidence')); await p.waitForTimeout(500);
  await p.screenshot({ path: path.join(OUT, 'victim-evidence.png') });
  await p.evaluate(() => openTab('deadlines')); await p.waitForTimeout(500);
  await p.screenshot({ path: path.join(OUT, 'victim-deadlines.png') });
  await p.locator('.orch').screenshot({ path: path.join(OUT, 'agent-cards.png') });
  await b.close();
})();
